import { open, ran, closeRunDetails } from './lib.mjs';
const { browser, page } = await open({ width: 1600, height: 900, dsf: 3 });
const settled = () => page.waitForFunction(() => { const t = (document.querySelector('.status') || {}).textContent || ''; return /Last run/.test(t) && !/Screening options/.test(t); }, null, { timeout: 600000, polling: 500 });
await ran(page);
await page.getByRole('button', { name: 'General settings' }).click();
await page.locator('#gs-site-beta').check();
await page.getByRole('button', { name: 'Close settings' }).click();
await page.locator('#open-study-file').setInputFiles('shots4/study.json');
await page.waitForFunction(() => /Opened/.test(document.body.innerText), null, { timeout: 60000 });
await page.waitForTimeout(3000); await settled(); await page.waitForTimeout(1000);
const [st] = await Promise.all([page.waitForEvent('download', { timeout: 60000 }), page.locator('#save-study').click()]);
await st.saveAs('shots4/study2.json');
await page.waitForTimeout(600);
await closeRunDetails(page); await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'shots4/k01-saved.jpg', type: 'jpeg', quality: 92 });
const saved = await page.evaluate(() => [...document.querySelectorAll('p, div, span')].map((e) => e.innerText).find((x) => /^Study saved/.test(x)) || '');
const sb = await page.getByText(/^Study saved/).first().boundingBox().catch(() => null);
console.log(JSON.stringify({ saved, sb }));
await page.locator('#open-study-file').setInputFiles('shots4/study2.json');
await page.waitForFunction(() => /Re-run matches|re-run differs|different result/.test(document.body.innerText), null, { timeout: 600000, polling: 500 });
await page.waitForTimeout(1000); await closeRunDetails(page); await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'shots4/k02-reopened.jpg', type: 'jpeg', quality: 92 });
const msg = await page.evaluate(() => [...document.querySelectorAll('p, div, span')].map((e) => e.innerText).find((x) => /Re-run matches/.test(x) && x.length < 600) || '');
const mb = await page.getByText(/Re-run matches/).first().boundingBox().catch(() => null);
console.log(JSON.stringify({ msg, mb }));
await browser.close();
