// Prepares the offline map of Europe (work package 1) from Natural Earth 1:50m country boundaries (public domain),
// as packaged by world-atlas (ISC licence), decoded with topojson-client (ISC). Run at each release:
//   node tools/make-map-data.mjs [path/to/world-atlas/countries-50m.json]
// Writes src/data/europe-map.js: the countries whose outline reaches the map window, as rings of [lon, lat] rounded
// to 0.01° (about 1 km), with the ISO code of the 31 built-in countries. The program bundles this file and never
// fetches map data.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const topo = require('topojson-client');
const src = process.argv[2] || require.resolve('world-atlas/countries-50m.json');
const world = JSON.parse(readFileSync(src, 'utf8'));
const fc = topo.feature(world, world.objects.countries);
const BBOX = { w: -32, e: 46, s: 33, n: 72 };
// ISO 3166-1 numeric → alpha-2 for the 31 built-in countries; names as fallback (Natural Earth leaves a few ids empty).
const NUM = { '040': 'AT', '056': 'BE', '100': 'BG', '191': 'HR', '196': 'CY', '203': 'CZ', '208': 'DK', '233': 'EE', '246': 'FI', '250': 'FR', '276': 'DE', '300': 'GR', '348': 'HU', '372': 'IE', '380': 'IT', '428': 'LV', '440': 'LT', '442': 'LU', '470': 'MT', '528': 'NL', '616': 'PL', '620': 'PT', '642': 'RO', '703': 'SK', '705': 'SI', '724': 'ES', '752': 'SE', '826': 'GB', '578': 'NO', '756': 'CH', '352': 'IS' };
const BYNAME = { Norway: 'NO', France: 'FR', 'United Kingdom': 'GB', Cyprus: 'CY', Czechia: 'CZ', 'Czech Rep.': 'CZ' };
const r2 = (x) => Math.round(x * 100) / 100;
const out = [];
for (const f of fc.features) {
  const polys = f.geometry ? (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : []) : [];
  const rings = [];
  for (const poly of polys) {
    const outer = poly[0];
    const inBox = outer.some(([lon, lat]) => lon >= BBOX.w && lon <= BBOX.e && lat >= BBOX.s && lat <= BBOX.n);
    if (!inBox) continue;
    for (const ring of poly) {
      const pts = [];
      for (const [lon, lat] of ring) {
        const p = [r2(lon), r2(lat)];
        const last = pts[pts.length - 1];
        if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
      }
      if (pts.length >= 4) rings.push(pts);
    }
  }
  if (!rings.length) continue;
  const name = f.properties && f.properties.name ? f.properties.name : String(f.id);
  const iso2 = NUM[String(f.id).padStart(3, '0')] || BYNAME[name] || null;
  out.push({ name, iso2, rings });
}
out.sort((a, b) => a.name.localeCompare(b.name));
const missing = Object.values(NUM).filter((c) => !out.some((x) => x.iso2 === c));
if (missing.length) throw new Error(`countries not found: ${missing.join(', ')}`);
mkdirSync(new URL('../src/data/', import.meta.url), { recursive: true });
const body = `// Generated by tools/make-map-data.mjs from Natural Earth 1:50m admin-0 countries (public domain, naturalearthdata.com),
// packaged by world-atlas 2.0.2 (ISC). Do not edit by hand. Rings are [lon, lat] rounded to 0.01°.
export const MAP_SOURCE = { name: 'Natural Earth 1:50m admin-0 countries', licence: 'public domain', package: 'world-atlas 2.0.2 (ISC)', resolution: '0.01°', bbox: ${JSON.stringify(BBOX)} };
export const MAP_COUNTRIES = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/data/europe-map.js', import.meta.url), body);
console.log(`${out.length} countries, ${out.reduce((a, c) => a + c.rings.reduce((b, r) => b + r.length, 0), 0)} points, ${(body.length / 1024).toFixed(0)} kB; built-in found: ${out.filter((x) => x.iso2).length}`);
