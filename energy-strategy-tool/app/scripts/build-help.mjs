// Builds src/data/help-t1.js: the numbers behind the "?" next to every parameter (work package 31; owner 2026-11-07,
// OPEN-QUESTIONS 181, 183, 184). Run once at each release (no network): the T1 reference example is run, and for its
// best option every parameter with a low–high range is set to its low and then its high value, one at a time, and the
// option re-evaluated, giving the change in its LCOE and its present-value cost. A parameter whose change moves neither
// is "no effect in this example"; a technology T1's best option does not use is named as such.
//
// Usage: node scripts/build-help.mjs   (from energy-strategy-tool/app; about one to three minutes)

import { writeFileSync } from 'node:fs';
import { referenceT1, normalizeInputs, getRegistry, TECH } from '../src/engine/defaults.js';
import { runModel } from '../src/engine/run.js';
import { buildContext } from '../src/engine/context.js';
import { evaluateOption } from '../src/engine/option.js';
import { choiceKey } from '../src/engine/generator.js';

const OUT = new URL('../src/data/help-t1.js', import.meta.url);
const START = '2027-01';
const t0 = Date.now();
const inputs = referenceT1({ analysisStart: START });
inputs.settings.generationCap = 400; // a quick T1 run for the example's best option (the user guide uses the same study)
const run = runModel(inputs);
const best = run.options.slice().sort((a, b) => a.rank - b.rank)[0];
const base = normalizeInputs(run.inputs || inputs);
const evalWith = (inp) => {
  const e = evaluateOption(buildContext(inp), best.v, { skipLayout: true });
  return { lcoe: e.eco.lcoe, npv: e.eco.npvCost };
};
const b = evalWith(base);
const reg = getRegistry();
const get = (o, path) => path.split('.').reduce((a, k) => (a == null ? a : a[k]), o);
const setIn = (o, path, x) => { const ks = path.split('.'); let a = o; for (let i = 0; i < ks.length - 1; i++) { if (a[ks[i]] == null || typeof a[ks[i]] !== 'object') return false; a = a[ks[i]]; } a[ks[ks.length - 1]] = x; return true; };
// Technologies the best option uses (sized above zero).
const used = new Set();
const sz = best.sizing || {};
for (const x of Object.values(sz)) for (const y of Array.isArray(x) ? x : [x]) if (y && typeof y === 'object' && y.tech && (y.mw > 0 || y.units > 0)) used.add(y.tech);
if ((sz.solarRoofMWp || 0) + (sz.solarGroundMWp || 0) > 0) used.add('solar');
if (sz.windMW > 0) used.add('wind');
if (sz.storage && sz.storage.mw > 0) used.add('battery');
if (best.v.C1 !== 'islanded') { used.add('substation'); }
console.log('used:', [...used].join(', '));
const out = {};
let n = 0;
for (const [path, r] of Object.entries(reg)) {
  if (typeof r.value !== 'number' || !Number.isFinite(r.low) || !Number.isFinite(r.high) || r.low === r.high) continue;
  const top = path.split('.')[0];
  if (top === 'spatial' || top === 'site' || top === 'view' || top === 'sensitivity' || top === 'uncertainty' || top === 'weights') continue;
  const res = {};
  if (top === 'tech') {
    const [, id, param] = path.split('.');
    const t = TECH[id];
    if (!t || !t.p || !(param in t.p)) continue;
    const keep = t.p[param];
    for (const [side, x] of [['low', r.low], ['high', r.high]]) { t.p[param] = x; try { res[side] = evalWith(base); } catch { res[side] = null; } }
    t.p[param] = keep;
    if (!used.has(id)) res.unused = TECH[id].name || id;
  } else {
    if (get(base, path) === undefined) continue;
    for (const [side, x] of [['low', r.low], ['high', r.high]]) {
      const inp = normalizeInputs(base);
      if (!setIn(inp, path, x)) { res[side] = null; continue; }
      try { res[side] = evalWith(inp); } catch { res[side] = null; }
    }
  }
  if (!res.low || !res.high) continue;
  const round = (x) => (Number.isFinite(x) ? Math.round(x * 100) / 100 : null);
  out[path] = [r.low, r.high, round(res.low.lcoe), round(res.high.lcoe), round(res.low.npv / 1e6), round(res.high.npv / 1e6), res.unused || null];
  n++;
}
const meta = {
  study: 'T1, the reference example (100 MW IT in four phases of 25 MW, 2028 to 2031, near Leamington Spa, Great Britain), 400 options sampled',
  builtAt: new Date().toISOString().slice(0, 10), option: best.name, optionKey: choiceKey(best.v),
  base: { lcoe: Math.round(b.lcoe * 100) / 100, npv: Math.round(b.npv / 1e5) / 10 },
  columns: ['low', 'high', 'lcoeAtLow', 'lcoeAtHigh', 'npvAtLow (€ m)', 'npvAtHigh (€ m)', 'technology not used'],
  params: out,
};
writeFileSync(OUT, `// Generated by scripts/build-help.mjs (work package 31) from the T1 reference example. Do not edit by hand: rebuild at release.\nexport const HELP_T1 = ${JSON.stringify(meta)};\n`);
console.log(`${n} parameters, best option ${best.name}, LCOE €${b.lcoe.toFixed(1)}/MWh; ${((Date.now() - t0) / 1000).toFixed(0)} s`);
